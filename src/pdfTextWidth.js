export function textWidth(text, fontSize, bold = false, font = FORM_FONT) {
    const widths = WIDTHS[font][bold ? "bold" : "regular"];
    let total = 0;
    for (const ch of String(text)) total += widths[ch.codePointAt(0) - 32] ?? 600;
    return (total / 1000) * fontSize;
}
